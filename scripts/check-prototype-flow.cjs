// Exercises real prototype API code with isolated in-memory browser storage.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const originalResolve = Module._resolveFilename;
Module._resolveFilename = function (name, parent, ...rest) {
  return originalResolve.call(this, name.startsWith('@/') ? path.join(root, 'src', name.slice(2)) : name, parent, ...rest);
};
require.extensions['.ts'] = (module, filename) => {
  const source = fs.readFileSync(filename, 'utf8');
  module._compile(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
};
const storage = new Map();
global.window = { dispatchEvent() {} };
global.localStorage = { getItem: (key) => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, String(value)), removeItem: (key) => storage.delete(key) };
(async () => {
  const api = require(path.join(root, 'src/lib/mockApi/index.ts'));
  const listing = await api.createListing({ sellerId: 'prototype-test-seller', title: 'Prototype test car', make: 'Porsche', model: '911', year: 2026, mileage: 0, price: 400000, mediaPath: 'photos_only', photos: Array.from({ length: 10 }, (_, i) => `https://example.test/photo-${i}.jpg`), status: 'pending_review' });
  assert.equal(listing.mileage, 0, 'Zero mileage must remain zero');
  assert.equal(listing.videoUrl, undefined, 'Photo path must remain static');
  assert.equal(await api.getListingBySlug(listing.slug), null, 'Pending listing must not be public');
  assert((await api.getListings({ sellerId: listing.sellerId })).some((item) => item.id === listing.id), 'Seller must see pending inventory');
  await api.approveListing(listing.id, 'Prototype test approval');
  assert.equal((await api.getListingBySlug(listing.slug)).status, 'live', 'Approval must publish the listing');
  assert((await api.getListings({ status: 'live' })).some((item) => item.id === listing.id), 'Approved listing must appear in live inventory');
  await api.logLead(listing.id, 'whatsapp');
  await api.logLead(listing.id, 'call');
  const contacted = await api.getListingById(listing.id);
  assert.equal(contacted.privateStats.whatsappLeads, 1);
  assert.equal(contacted.privateStats.callLeads, 1);
  await api.rejectListing(listing.id, 'Replace blurry photos');
  assert.equal(await api.getListingBySlug(listing.slug), null, 'Rejected listing must not be public');
  assert.equal((await api.getListingById(listing.id)).rejectionReason, 'Replace blurry photos');
  await api.approveListing(listing.id);
  await api.archiveListing(listing.id);
  assert.equal(await api.getListingBySlug(listing.slug), null, 'Archived listing must not be public');
  assert((await api.getListingById(listing.id)).auditHistory.length >= 4, 'Lifecycle actions must retain history');
  const community = require(path.join(root, 'src/lib/prototypeCommunity.ts'));
  const fixture = Array.from({ length: 20 }, (_, index) => ({ ...listing, id: `feed-${index}`, status: 'live', mediaPath: 'ready_video', videoUrl: '/sample.mp4' }));
  const photos = Array.from({ length: 10 }, (_, index) => ({ ...listing, id: `photo-${index}`, status: 'live' }));
  const feed = community.buildDiscoveryFeed([...photos, ...fixture, { ...listing, id: 'hidden', status: 'pending_review' }]);
  assert.deepEqual(feed.map((item, index) => item.mediaPath === 'photos_only' ? index : -1).filter((index) => index >= 0), [7, 15], 'Photo cards must follow seven videos, including repeated groups');
  assert.equal(community.buildDiscoveryFeed(photos).length, 0, 'A photo-only inventory must not masquerade as a video feed');
  assert.equal(community.buildDiscoveryFeed([...fixture.slice(0, 6), ...photos]).length, 6);
  community.toggleInteraction('saves', listing.id, 'buyer-a');
  community.toggleInteraction('likes', listing.id, 'buyer-a');
  assert.deepEqual(community.readCommunity().saves['buyer-a'], [listing.id]);
  assert.equal(community.readCommunity().saves['buyer-b'], undefined, 'Saved cars must be account scoped');
  community.toggleInteraction('saves', listing.id, 'buyer-a');
  assert.equal(community.readCommunity().saves['buyer-a'].length, 0, 'Unsave must persist');
  const comment = community.addPrototypeComment({ listingId: listing.id, userId: 'buyer-a', userName: 'Test buyer', content: 'Is this available?' });
  const reply = community.addPrototypeComment({ listingId: listing.id, userId: 'buyer-b', userName: 'Test seller', content: 'Yes', parentId: comment.id });
  community.submitPrototypeReport({ targetType: 'comment', targetId: comment.id, targetTitle: comment.content, reason: 'Inappropriate content', details: 'Local test report', reporterEmail: 'test@example.test' });
  const report = (await api.getReports()).find((item) => item.targetId === comment.id);
  assert(report, 'Buyer reports must reach admin moderation');
  await api.handleReportAction(report.id, 'removed');
  assert(community.readCommunity().comments.find((item) => item.id === comment.id).hidden);
  assert(community.readCommunity().comments.find((item) => item.id === reply.id).hidden, 'Removing a thread hides its replies');
  assert.throws(() => community.addPrototypeComment({ listingId: listing.id, userId: 'buyer-b', userName: 'Buyer', content: 'Another reply', parentId: comment.id }));
  console.log('PASS: listing lifecycle, zero mileage, static photos, separate leads, feed spacing, short/empty feeds, private likes/saves, comments/replies, reports and admin removal');
})().catch((error) => { console.error(error); process.exitCode = 1; });
